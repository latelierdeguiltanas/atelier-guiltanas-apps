'use strict';
const assert = require('node:assert/strict');
const vm = require('node:vm');
const path = require('node:path');
const {load} = require('./forge_product_runner');
for (const file of ['index.html']) {
  const {html,db} = load(path.resolve(__dirname,'..',file));
  const T=db.tables, geo='history:campaigns', pro='history:courtier';
  const d={age:true,ageId:'venerable',histories:true,geoId:geo,proId:pro,acquisitionPurchases:[]};
  const host={markup:'',insertAdjacentHTML(_,s){this.markup+=s},querySelectorAll(selector){
    const key=selector.includes('remove')?'rank-remove':'rank-add';
    return [...this.markup.matchAll(new RegExp('data-'+key+'="([^"]+)"(?: data-rank="([^"]+)")?','g'))].map(m=>({dataset:key==='rank-add'?{rankAdd:m[1],rank:m[2]}:{rankRemove:m[1]}}));
  }};
  // Capture the listeners attached to the buttons generated by the production renderer.
  const query=host.querySelectorAll.bind(host);
  host.querySelectorAll=function(selector){return this[selector]=query(selector)};
  const box={T,d,$:()=>host,draftGrantedRanks:()=>new Map(),profile:()=>null,ability:()=>null,pAbility:()=>null,esc:String,pathLabel:id=>id};
  box.render=()=>{host.markup='';box.renderAgePurchases([])};
  vm.createContext(box);
  vm.runInContext(html.split('\n').filter(l=>l.startsWith('function renderAgePurchases(')).at(-1),box);
  const click=(selector,id)=>{const key=selector.includes('remove')?'rankRemove':'rankAdd';const b=host[selector].find(b=>b.dataset[key]===id);assert.ok(b,'Missing usable button '+id);b.onclick()};
  box.render();
  for(const id of [geo,pro,geo,pro])click('[data-rank-add]',id);
  assert.match(host.markup,/restant : 0/);
  assert.equal(host['[data-rank-add]'].length,0);
  click('[data-rank-remove]',pro);
  assert.match(host.markup,/restant : 1/);
  click('[data-rank-add]',pro);
  assert.match(host.markup,/restant : 0/);
  assert.deepEqual(JSON.parse(JSON.stringify(d.acquisitionPurchases)),[{pathId:geo,rank:2},{pathId:pro,rank:2},{pathId:geo,rank:3},{pathId:pro,rank:3}]);
  const serialized=JSON.stringify(d);
  Object.assign(d,JSON.parse(serialized));box.render();
  assert.equal(JSON.stringify(d),serialized);
  console.log('PASS '+file+' rendered history buttons: buy, undo, rebuy, reopen');
}
