'use strict';
const assert=require('node:assert/strict'),vm=require('node:vm');
const {load,standardState,withRank}=require('./forge_product_runner');
const {bounds,hash}=require('./n1_druide_runtime_bundle.cjs');
const {db,engine,html}=load(),[start,end]=bounds(html),scope={};
vm.runInNewContext(html.slice(start,end),scope);
const A=scope.FOHAbilityRuntime,path='classpath:voie-du-protecteur:class-druide:cof2-lb-2024';
const draft=standardState(db,'class:druide:cof2-lb-2024',path);
draft.baseCaracs={for:0,agi:1,con:2,per:3,int:0,vol:1,cha:-1};
draft.peupleChoices.humainStat='for';
const {sticky,errors}=engine.computeCharacterN1(withRank(db,draft,path,2));
assert.equal(errors.length,0);
const [berries,forest]=[1,2].map(rank=>sticky.abilityRuntimeCatalog.find(a=>a.pathId===path&&a.rank===rank));
assert.equal(berries.quotas.length,0);
assert.equal(berries.targetQuotas[0].period,'day');
assert.equal(forest.ritualMinutes,30);
assert.equal(forest.quotas[0].resolvedMax,1);
const initial=A.begin(sticky.characterState,db);
const snapshot=JSON.stringify(initial);
assert.throws(()=>A.use(initial,berries.id,db),/arbre ou buisson/);
const cast=A.use(initial,berries.id,db,{livingPlant:true});
const again=A.use(cast,berries.id,db,{livingPlant:true});
assert.equal(again.magicBerries.count,6);
assert.equal(again.resources.mana.current,initial.resources.mana.current-2);
assert.throws(()=>A.consumeMagicBerry(again,berries.id,db,{targetId:'lea',elapsedMinutes:0}),/une minute/);
const serve=(state,targetId)=>A.consumeMagicBerry(state,berries.id,db,{targetId,elapsedMinutes:1});
const fed=serve(again,'lea');
assert.equal(fed.lastUse.healingBonus,2);
assert.equal(fed.lastUse.providesMeal,true);
assert.equal(fed.resources.mana.current,again.resources.mana.current);
assert.throws(()=>serve(fed,'lea'),/déjà/);
const resumed=JSON.parse(JSON.stringify(serve(fed,'math')));
assert.equal(resumed.magicBerries.count,4);
assert(A.validate(resumed,db));
assert.throws(()=>serve(A.recover(resumed,'combat',db),'lea'),/déjà/);
assert.equal(serve(A.recover(resumed,'day',db),'lea').magicBerries.count,3);
const legacy=JSON.parse(snapshot);
delete legacy.magicBerries;
legacy.used[berries.id]={day:1};
assert.equal(A.use(legacy,berries.id,db,{livingPlant:true,perception:3}).used[berries.id],undefined);
assert.throws(()=>A.use(initial,forest.id,db,{ritualMinutesElapsed:29}),/30 minutes/);
const awakened=A.use(initial,forest.id,db,{ritualMinutesElapsed:30});
assert.equal(awakened.resources.mana.current,initial.resources.mana.current-2);
assert.throws(()=>A.use(A.recover(awakened,'combat',db),forest.id,db,{ritualMinutesElapsed:30}),/épuisées/);
assert.equal(A.use(A.recover(awakened,'full',db),forest.id,db,{ritualMinutesElapsed:30}).used[forest.id].day,1);
assert.equal(JSON.stringify(initial),snapshot);
console.log(JSON.stringify({status:'PASS',indexSha256:hash(html),checks:['Baies : deux lancements, six fruits','Consommation : délai, bénéficiaire et mana','Quotas, sauvegarde et ancien compteur','Forêt : durée, mana et récupération','État initial intact']}));
